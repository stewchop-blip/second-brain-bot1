"""
System prompts for the three bot modes.
Rewritten for clarity: friendly tone, no "AI" word, consistent structure,
short verdict first. Each mode follows a fixed template so users learn fast.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class SystemPrompt:
    """System prompt with metadata."""
    name: str
    prompt: str
    description: str
    example_user: str
    example_bot: str


