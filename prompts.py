# Registry for easy access
MODES = {
    "check_idea": CHECK_IDEA,
    "check_message": CHECK_MESSAGE,
    "help_choose": HELP_CHOOSE,
    "ask": ASK,
}


def get_mode(key: str) -> SystemPrompt:
    """Get mode by key, raise if not found."""
    if key not in MODES:
        raise ValueError(f"Unknown mode: {key}. Available: {list(MODES.keys())}")
    return MODES[key]


def list_modes() -> list[SystemPrompt]:
    """Return all modes as list."""
    return list(MODES.values())
