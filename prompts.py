"""
System prompts for the three bot modes.
Optimized for concise, structured responses in Russian.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class SystemPrompt:
    """System prompt with metadata."""
    name: str
    prompt: str
    description: str
    example_user: str
    example_bot: str


