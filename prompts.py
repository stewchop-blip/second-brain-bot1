"""
System prompts for the bot modes.
Rewritten for clarity: friendly tone, no "AI" word, consistent structure,
short verdict first. "Спросить" is the universal entry with conversation context.
"""
from dataclasses import dataclass


@dataclass(frozen=True)
class SystemPrompt:
    """System prompt with metadata."""
    name: str
    prompt: str
    description: str
    example_user: str
    example_bot: str


